
<p>
    Via this page you can, simply and without costs, produce
    evidence of "being alive". Certain (live)insurances ask
    regularly for such a <em>Attestatio de Vita</em>.
</p>

<div id="result" class="alert" hidden></div>

<h3>Reveal personal data</h3>
<p>
    Via the button below you will be asked to reveal via your Yivi
    app the following data: your family name, initials and data of
    birth. It will be checked whether they are at most 14 days
    old, that is, that they have been loaded into your Yivi app
    less than 14 days ago.
</p>

<div style="text-align: center; margin-bottom: 25px">
    <button class="custom-button" id="verification">Reveal data for Attestatio de Vita</button>
</div>

<h3>Background</h3>
<ul>
    <li>You can reveal the requested data via
        the <a href="https://yivi.app/#download">Yivi
            app</a> on your mobile phone.</li>
    <li>You need to have already loaded the relevant personal data
        in your Yivi app.  In the Netherlands these data can be
        obtained online from government registers via
        municipalities.</li>
    <li>These so-called BRP data can be loaded (or refreshed) into
        your Yivi app
        via <a href="https://yivi.nijmegen.nl/login">this
        link</a>.</li>
    <li>After this demo your data will be removed immediately.
</ul>

